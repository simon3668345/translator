'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(ROOT, 'style.css'), 'utf8');
const favicon = fs.readFileSync(path.join(ROOT, 'favicon.png'));

let out = html
  .replace(
    '<link rel="icon" type="image/png" href="favicon.png">',
    '<link rel="icon" href="data:image/png;base64,' + favicon.toString('base64') + '">'
  )
  .replace('<link rel="stylesheet" href="style.css">', '<style>\n' + css + '\n</style>');

for (const f of ['font.js', 'sprites.js', 'audio.js', 'game.js']) {
  const code = fs.readFileSync(path.join(ROOT, 'js', f), 'utf8');
  out = out.replace('<script src="js/' + f + '"></script>', '<script>\n' + code + '\n</script>');
}

if (out.includes('src="js/') || out.includes('href="style.css"') || out.includes('href="favicon.png"')) {
  throw new Error('inlining failed, external reference remains');
}

out = out.replace('<head>', '<head>\n<!-- generated by test/build-standalone.js - do not edit by hand -->');

const dest = path.join(ROOT, 'standalone.html');
fs.writeFileSync(dest, out);
console.log('wrote ' + dest + ' (' + out.length + ' bytes)');
